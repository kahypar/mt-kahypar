    template<typename TypeTraits>
    typename EvoPartitioner<TypeTraits>::PartitionedHypergraph EvoPartitioner<TypeTraits>::partition(
        Hypergraph& hypergraph, Context& context, TargetGraph* target_graph) {

        EvoPartitioner<TypeTraits>::configurePreprocessing(hypergraph, context);
        EvoPartitioner<TypeTraits>::setupContext(hypergraph, context, target_graph);

        io::printContext(context);
        io::printMemoryPoolConsumption(context);
        io::printInputInformation(context, hypergraph);

        #ifdef KAHYPAR_ENABLE_STEINER_TREE_METRIC
        bool map_partition_to_target_graph_at_the_end = false;
        if ( context.partition.objective == Objective::steiner_tree &&
            context.mapping.use_two_phase_approach ) {
        map_partition_to_target_graph_at_the_end = true;
        context.partition.objective = Objective::km1;
        context.setupGainPolicy();
        }
        #endif

        // DISABLED -- Individuals have incorrect indexing after preprocessing
        // ################## PREPROCESSING ##################
        utils::Timer& timer = utils::Utilities::instance().getTimer(context.utility_id);
        timer.start_timer("preprocessing", "Preprocessing");
        // DegreeZeroHypernodeRemover<TypeTraits> degree_zero_hn_remover(context);
        // LargeHyperedgeRemover<TypeTraits> large_he_remover(context);
        // Partitioner<TypeTraits>::preprocess(hypergraph, context, target_graph);
        // EvoPartitioner<TypeTraits>::sanitize(hypergraph, context, degree_zero_hn_remover, large_he_remover);
        timer.stop_timer("preprocessing");

        // ################## EVOLUTIONARY PARTITIONING ##################
        DBG << "DEBUG: Calling generateInitialPopulation...";
        // The initial population is generated by calling the standard partitioner repeatedly.
        Population population;
        evolutionary::EvoStatistics stats;
        evolutionary::EvoRunLog log(context.evolutionary, evolutionary::currentTimestampMs());
        generateInitialPopulation(hypergraph, context, target_graph, population, stats, log);
        DBG << "DEBUG: generateInitialPopulation finished.";

        DBG << "DEBUG: Calling performEvolution...";
        performEvolution(hypergraph, context, target_graph, population, stats, log);
        DBG << "DEBUG: performEvolution finished.";

        log.writeFiles(stats);

        // ################## FINALIZATION ##################
        // After evolution, we take the best individual and create the final partition.
        PartitionedHypergraph final_partition(context.partition.k, const_cast<Hypergraph&>(hypergraph));
        
        std::vector<PartitionID> best_partition_vec = population.bestPartitionCopy();
        final_partition.doParallelForAllNodes([&](const HypernodeID& hn) {
            final_partition.setOnlyNodePart(hn, best_partition_vec[hn]);
        });
        final_partition.initializePartition();

        ASSERT([&] {
            bool success = true;
            if ( final_partition.hasFixedVertices() ) {
                for ( const HypernodeID& hn : final_partition.nodes() ) {
                    if ( final_partition.isFixed(hn) &&
                        final_partition.fixedVertexBlock(hn) != final_partition.partID(hn) ) {
                        LOG << "Node" << hn << "is fixed to block" << final_partition.fixedVertexBlock(hn)
                            << ", but is assigned to block" << final_partition.partID(hn);
                        success = false;
                    }
                }
            }
            return success;
        }(), "Some fixed vertices are not assigned to their corresponding block");

        // ################## POSTPROCESSING ##################
        timer.start_timer("postprocessing", "Postprocessing");
        // large_he_remover.restoreLargeHyperedges(final_partition);
        // degree_zero_hn_remover.restoreDegreeZeroHypernodes(final_partition);
        // forceFixedVertexAssignment(partitioned_hypergraph, context);
        timer.stop_timer("postprocessing");

        #ifdef KAHYPAR_ENABLE_STEINER_TREE_METRIC
            if ( map_partition_to_target_graph_at_the_end ) {
            ASSERT(target_graph);
            context.partition.objective = Objective::steiner_tree;
            timer.start_timer("one_to_one_mapping", "One-To-One Mapping");
            InitialMapping<TypeTraits>::mapToTargetGraph(
                 final_partition, *target_graph, context);
            timer.stop_timer("one_to_one_mapping");
            }
        #endif

        if (context.partition.enable_logging) {
            io::printHypergraphInfo(final_partition.hypergraph(), context,
                                    "Uncoarsened Hypergraph", context.partition.show_memory_consumption);
            io::printStripe();
        }

        return final_partition;
    }


    template<typename TypeTraits>
    void EvoPartitioner<TypeTraits>::generateInitialPopulation(const Hypergraph& hg, Context& context, TargetGraph* target_graph, Population& population, evolutionary::EvoStatistics& stats, evolutionary::EvoRunLog& log) {
        context.partition.enable_logging = false;
        utils::Timer& timer = utils::Utilities::instance().getTimer(context.utility_id);
        auto start = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::high_resolution_clock::now().time_since_epoch());
        auto now = start;
        auto time_elapsed = now - start;
        auto duration = std::chrono::seconds(context.partition.time_limit);
        const bool enforce_time_limit = context.partition.time_limit > 0;

        // META-EVO LOGIC
        if (context.evolutionary.meta_evo_mode) {
            DBG << "DEBUG: Starting Meta-Evo Initial Population Generation";
            

            int target_pop_size = context.evolutionary.population_size;
            int solutions_per_run = context.evolutionary.meta_evo_solutions_per_run; // Default 5
            int num_meta_runs = (target_pop_size + solutions_per_run - 1) / solutions_per_run;

            for (int run = 0; run < num_meta_runs; run++) {
                now = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::high_resolution_clock::now().time_since_epoch());
                if (context.partition.time_limit > 0 && (now - start) >= duration) {
                    DBG << "DEBUG: Meta-Evo aborted due to global time limit.";
                    break;
                }

                DBG << "DEBUG: Meta-Evo Run " << (run + 1) << "/" << num_meta_runs;

                // Setup Sub-Context
                Context sub_context(context);
                sub_context.evolutionary.meta_evo_mode = false; // Prevent recursion
                
                // Sub-runs use stopping criteria, NOT the global time limit
                sub_context.partition.time_limit = 0; 
                sub_context.evolutionary.improvement_rate_stopping.enabled = true;
                Population sub_population;
                evolutionary::EvoStatistics sub_stats;
                // Sub-runs write no log files
                sub_context.evolutionary.log_level = EvoLogLevel::none;
                evolutionary::EvoRunLog sub_log(sub_context.evolutionary, evolutionary::currentTimestampMs());

                // Adjust seed for sub-runs if in deterministic mode
                if (sub_context.partition.deterministic) {
                    sub_context.partition.seed += run + 1; // +1 to differ from main run
                }
                generateInitialPopulation(hg, sub_context, target_graph, sub_population, sub_stats, sub_log);
                performEvolution(hg, sub_context, target_graph, sub_population, sub_stats, sub_log);

                DBG << "DEBUG: Finished generating sub population";

                // Extract Best Individuals
                Individuals best_individuals = sub_population.listOfBest(solutions_per_run);
                for (auto individual : best_individuals) {
                    if (population.size() >= static_cast<size_t>(target_pop_size)) break;
                    population.addStartingIndividual(individual, context);
                    stats.recordInitial(individual->fitness(), context.evolutionary.iteration, evolutionary::currentTimestampMs());
                }
            }
            auto end_time_meta = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::high_resolution_clock::now().time_since_epoch());
            auto meta_duration = std::chrono::duration_cast<std::chrono::seconds>(end_time_meta - start);
            // Update the global limit for the subsequent evolution phase
            if (context.partition.time_limit > 0) {
                context.partition.time_limit -= meta_duration.count();
                if (context.partition.time_limit < 1) context.partition.time_limit = 1; // leave at least 1 sec
            }

            context.partition.enable_logging = true;
            return;
        }

        // if deterministic, save original seed to reset after initial population generation
        const int original_seed = context.partition.seed;
        if (context.partition.deterministic && context.partition.enable_benchmark_mode) {
            context.partition.seed = 0;
        }
               
        // INITIAL POPULATION
        if (context.evolutionary.dynamic_population_size) {
            HighResClockTimepoint start = std::chrono::high_resolution_clock::now();
            timer.start_timer("evolutionary", "Evolutionary");
            auto fitness = createInsertIndividual(hg, context, target_graph, population)->fitness();
            now = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::high_resolution_clock::now().time_since_epoch());
            stats.recordInitial(fitness, context.evolutionary.iteration, now.count());

            timer.stop_timer("evolutionary");

            ++context.evolutionary.iteration;
            int dynamic_population_size = std::round(context.evolutionary.dynamic_population_amount_of_time
                                                    * context.partition.time_limit
                                                    / timer.get("evolutionary"));
            int minimal_size = std::max(dynamic_population_size, 3);

            context.evolutionary.population_size = std::min(minimal_size, 50);
            // limit kway combine to population size
            context.evolutionary.kway_combine = std::min(context.evolutionary.kway_combine,
                                                        int(context.evolutionary.population_size));

            LOG << context.evolutionary.population_size;
            DBG << population;

            // increment seed if deterministic
            if (context.partition.deterministic) {
                context.partition.seed++;
            }
        }
        DBG << "DEBUG: Initial population target size =" << context.evolutionary.population_size;
        int iteration = 0;

        while (population.size() < context.evolutionary.population_size &&
            (!enforce_time_limit || time_elapsed <= duration)) {
            DBG << "DEBUG: Initial pop loop - Iteration" << iteration << ", Pop size:" << population.size();
            ++context.evolutionary.iteration;
            timer.start_timer("evolutionary", "Evolutionary");
           
            auto cur = createInsertIndividual(hg, context, target_graph, population)->fitness();
            timer.stop_timer("evolutionary");
            now = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::high_resolution_clock::now().time_since_epoch());
            stats.recordInitial(cur, context.evolutionary.iteration, now.count());

            iteration++;
            time_elapsed = now - start;

            // increment seed if in benchmark mode
            
            if (context.partition.deterministic) {
                context.partition.seed++;
            }
        }

        // reset seed after initial population generation
        if (context.partition.deterministic && context.partition.enable_benchmark_mode) {
            context.partition.seed = original_seed;
        }

        log.recordDiffMatrix(population);

        context.evolutionary.time_elapsed = time_elapsed;
        context.partition.enable_logging = true;
    }
    template<typename TypeTraits>
    std::shared_ptr<Individual> EvoPartitioner<TypeTraits>::createIndividual(const Hypergraph &input_hg, Context &context,
                                                                       TargetGraph *target_graph) {
        Hypergraph hypergraph_copy = input_hg.copy(parallel_tag_t{});

        DBG << "DEBUG: generateIndividual: Calling standard partitioner...";

        Context ip_context(context);

        // If we are not using individual part weights, ensure max_part_weights is empty
        if (!ip_context.partition.use_individual_part_weights) {
            ip_context.partition.max_part_weights.clear();
        }

        // PREPROCESSING
        DegreeZeroHypernodeRemover<TypeTraits> degree_zero_hn_remover(context);
        LargeHyperedgeRemover<TypeTraits> large_he_remover(context);
        Partitioner<TypeTraits>::preprocess(hypergraph_copy, context, target_graph);
        EvoPartitioner<TypeTraits>::sanitize(hypergraph_copy, context, degree_zero_hn_remover, large_he_remover);

        EvoPartitioner<TypeTraits>::PartitionedHypergraph partitioned_hypergraph;
        // PartitionedHypergraph partitioned_hypergraph =
        //     Partitioner<TypeTraits>::partition(hypergraph_copy, ip_context, target_graph);
        vec<EdgeMetadata> edge_md;
        if (context.partition.mode == Mode::direct) {
            partitioned_hypergraph = Multilevel<TypeTraits>::partition(hypergraph_copy, std::move(edge_md), context, target_graph);
        } else if (context.partition.mode == Mode::recursive_bipartitioning) {
            partitioned_hypergraph = RecursiveBipartitioning<TypeTraits>::partition(hypergraph_copy,std::move(edge_md), context, target_graph);
        } else if (context.partition.mode == Mode::deep_multilevel) {
            partitioned_hypergraph = DeepMultilevel<TypeTraits>::partition(hypergraph_copy, context);
        } else {
            throw InvalidParameterException("Invalid partitioning mode!");
        }
        DBG << "DEBUG: generateIndividual: Partitioner finished.";

        // POSTPROCESSING
        large_he_remover.restoreSinglePinAndLargeHyperedges(partitioned_hypergraph);
        degree_zero_hn_remover.restoreDegreeZeroHypernodes(partitioned_hypergraph);
        //Partitioner<TypeTraits>::forceFixedVertexAssignment(partitioned_hypergraph, context);
        return std::make_shared<Individual>(partitioned_hypergraph, context);
    }

    template<typename TypeTraits>
    const std::shared_ptr<Individual>  EvoPartitioner<TypeTraits>::createInsertIndividual(const Hypergraph& input_hg, Context& context, TargetGraph* target_graph, Population& population) {
        auto individual = createIndividual(input_hg, context, target_graph);
        population.addStartingIndividual(individual, context);
        return individual;
    }

    template<typename TypeTraits>
    std::vector<PartitionID> EvoPartitioner<TypeTraits>::createPartition(const Hypergraph& input_hg, Context& context, TargetGraph* target_graph) {
        auto individual= createIndividual(input_hg, context, target_graph);
        return individual->partition();
    }

    template<typename TypeTraits>
    bool EvoPartitioner<TypeTraits>::insert_individual_into_population(
        std::shared_ptr<Individual> individual,
        const Context& context,
        Population& population,
        evolutionary::EvoStatistics& stats,
        evolutionary::EvoRunLog& log,
        int iteration,
        evolutionary::EvoOperator op,
        HyperedgeWeight parent_best_fitness,
        size_t dist_to_parent) {
        individual->setBirthIteration(iteration);
        individual->setOriginOperator(evolutionary::operatorName(op));
        individual->setParentBestFitness(parent_best_fitness);
        individual->setDistToParent(dist_to_parent);
        const long long ts_ms = evolutionary::currentTimestampMs();
        const HyperedgeWeight offspring_fit = individual->fitness();
        const InsertionDetails ins_details = population.insertWithDetails(std::move(individual), context);

        const evolutionary::OffspringEvent event {
            iteration,
            ts_ms,
            op,
            parent_best_fitness,
            offspring_fit,
            dist_to_parent,
            ins_details.was_accepted,
            ins_details.dist_to_replaced,
            ins_details.min_dist_pop,
            ins_details.was_accepted ? static_cast<int>(ins_details.position) : -1
        };
        const bool was_new_best = stats.recordOffspring(event);

        if (log.logsOffspring()) {
            log.recordOffspring(event, was_new_best);
        }
        if (log.isPopulationSnapshotDue(iteration)) {
            log.recordDiffMatrix(population);
            log.recordPopulationSummary(population, iteration, ts_ms);
        }
        return ins_details.was_accepted;
    }

    template<typename TypeTraits>
    CombineResult EvoPartitioner<TypeTraits>::performCombine(
        const Hypergraph& input_hg,
        const Context& context,
        TargetGraph* target_graph,
        Population& population,
        ContextModifierParameters modified_combine_params,
        std::mt19937* rng
        ) {

        EvoCombineStrategy combine_strategy = pick::decideNextCombination(context, rng);
        std::shared_ptr<Individual> child;
        HyperedgeWeight parent_best_fit = 0;
        size_t dist = 0;

        switch (combine_strategy) {
            case EvoCombineStrategy::basic: {
                std::vector<size_t> parents;
                auto best_individual = population.sampleKParentsReturnBest(parents, context.evolutionary.kway_combine,
                                                                           context.partition.deterministic, rng);
                parent_best_fit = best_individual ? best_individual->fitness() : 0;
                std::vector<PartitionID> best_partition = best_individual->partition();
                std::vector<std::vector<PartitionID>> parent_partitions;
                for (auto parent_id : parents) {
                    parent_partitions.push_back(population.partitionCopyAt(parent_id));
                }
                child = combine::combineParentsWithVCycle<TypeTraits>(parent_partitions, best_partition, context, target_graph, input_hg);
                if (best_individual && child) {
                    dist = Population::distanceBetween(*best_individual, *child, false);
                }
                break;
            }
            case EvoCombineStrategy::edge_frequency: {
                auto best_ind = population.bestInd();
                parent_best_fit = best_ind ? best_ind->fitness() : 0;
                child = combine::usingMultiEdgeFrequency<TypeTraits>(input_hg, population, context, target_graph, rng);
                if (best_ind && child) {
                    dist = Population::distanceBetween(*best_ind, *child, false);
                }
                break;
            }
            case EvoCombineStrategy::synthetic_parent: {
                if (context.evolutionary.modified_combine_mixed) {
                    modified_combine_params = pick::decideContextModificationParameters(context, rng);
                }
                auto best_ind = population.randomIndividual(context.partition.deterministic, rng);
                parent_best_fit = best_ind ? best_ind->fitness() : 0;
                child = combine::usingSyntheticSecondParent<TypeTraits>(input_hg, population, target_graph, modified_combine_params, context, rng);
                if (best_ind && child) {
                    dist = Population::distanceBetween(*best_ind, *child, false);
                }
                break;
            }
            case EvoCombineStrategy::UNDEFINED:
                break;
        }
        if (child) {
            child->setParentBestFitness(parent_best_fit);
            child->setDistToParent(dist);
        }
        return { child, combine_strategy, parent_best_fit, dist };
    }

    template<typename TypeTraits>
    MutationResult EvoPartitioner<TypeTraits>::performMutation(
        const Hypergraph &input_hg,
        const Context &context,
        TargetGraph *target_graph,
        Population &population,
        std::mt19937 *rng) {
        Hypergraph hypergraph = input_hg.copy(parallel_tag_t{});

        auto parent_ind = population.randomIndividual(context.partition.deterministic, rng);
        HyperedgeWeight parent_fit = parent_ind ? parent_ind->fitness() : 0;
        const std::vector rnd_ind_partition(parent_ind ? parent_ind->partition() : population.randomIndividualPartitionCopy(context.partition.deterministic, rng));
        EvoMutateStrategy mutate_strategy = pick::decideNextMutation(context, rng);
        std::shared_ptr<Individual> child;
        switch (mutate_strategy) {
            case EvoMutateStrategy::new_initial_partitioning_vcycle:
                child = mutate::vCycleWithNewInitialPartitioning<TypeTraits>(hypergraph, rnd_ind_partition, target_graph,
                                                                            context);
                break;
            case EvoMutateStrategy::vcycle:
                child = mutate::vCycle<TypeTraits>(hypergraph, rnd_ind_partition, target_graph, context);
                break;
            case EvoMutateStrategy::UNDEFINED:
                throw UnsupportedOperationException("Next Mutation Strategy is UNDEFINED");
        }
        size_t dist = 0;
        if (parent_ind && child) {
            dist = Population::distanceBetween(*parent_ind, *child, false);
        }
        if (child) {
            child->setParentBestFitness(parent_fit);
            child->setDistToParent(dist);
        }
        return { child, mutate_strategy, parent_fit, dist };
    }

    inline void disableTimerAndStatsEvo(const Context& context) {
        if ( context.type == ContextType::main && context.partition.mode == Mode::direct ) {
            utils::Utilities& utils = utils::Utilities::instance();
            parallel::MemoryPool::instance().deactivate_unused_memory_allocations();
            utils.getTimer(context.utility_id).disable();
            utils.getStats(context.utility_id).disable();
        }
    }

    inline void enableTimerAndStatsEvo(const Context& context) {
        if ( context.type == ContextType::main && context.partition.mode == Mode::direct ) {
            utils::Utilities& utils = utils::Utilities::instance();
            parallel::MemoryPool::instance().activate_unused_memory_allocations();
            utils.getTimer(context.utility_id).enable();
            utils.getStats(context.utility_id).enable();
        }
    }

    template<typename TypeTraits>
    void EvoPartitioner<TypeTraits>::performEvolution(const Hypergraph& hg, Context& context, TargetGraph* target_graph, Population& population, evolutionary::EvoStatistics& stats, evolutionary::EvoRunLog& log) {
        context.partition.enable_logging = false;
        int timelimit = context.partition.time_limit;
        utils::Timer& timer = utils::Utilities::instance().getTimer(context.utility_id);
        auto time_start = std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::high_resolution_clock::now().time_since_epoch());
        const bool enforce_time_limit = timelimit > 0;
        auto duration = std::chrono::seconds(timelimit) - context.evolutionary.time_elapsed;
        std::atomic<bool> stop_flag(false);

        const int total_threads = context.shared_memory.num_threads;
        int num_evo_workers = 0;
        int num_multilevel_threads = 0;

        if (context.evolutionary.num_threads_per_worker > 0) {
            num_multilevel_threads = std::min(total_threads, static_cast<int>(context.evolutionary.num_threads_per_worker));
            num_evo_workers = std::max(1, total_threads / num_multilevel_threads);
        } else {
            // Default behavior
            num_evo_workers = std::max(1, total_threads / 2);
            num_multilevel_threads = std::max(1, total_threads / num_evo_workers);
        }
        
        // Per-operator counters live in `stats`; this counter also hands out iteration / batch ids
        std::atomic<int> total_iterations(0);

        // State for stopping criterion
        double early_window_improvement_rate = -1.0;
        std::mutex stopping_criterion_mutex;

        // Calculate ContextModifierParameters once before any workers start
        ContextModifierParameters modified_combine_params;
        if (context.evolutionary.synthetic_parent_combine_weight > 0) {
            const double k_result = context.partition.k * context.evolutionary.modified_combine_k_multiplier;
            ASSERT(k_result >= 1.0, "k multiplier result must be >= 1: " << k_result);
            ASSERT(std::abs(k_result - std::round(k_result)) < 1e-10, 
                "k multiplier must result in whole number: " << k_result);
            
            const PartitionID absolute_k = static_cast<PartitionID>(std::round(k_result));
            const double absolute_epsilon = std::min(0.99, 
                context.partition.epsilon * context.evolutionary.modified_combine_epsilon_multiplier);
            
            modified_combine_params = ContextModifierParameters{
                .use_random_partitions = context.evolutionary.modified_combine_use_random_partitions,
                .use_degree_sorted_partitions = context.evolutionary.modified_combine_use_degree_sorted_partitions,
                .k = absolute_k,
                .epsilon = absolute_epsilon,
                .recursive_bipartitioning = context.evolutionary.modified_combine_recursive_bipartitioning
            };
        }

        timer.start_timer("evolutionary", "Evolutionary");

        LOG << "Starting evolutionary search with" << num_evo_workers << "workers, each using"
            << num_multilevel_threads << "threads for multilevel partitioning.";


        const auto create_worker_arenas = [&]() {
            std::vector<std::unique_ptr<tbb::task_arena>> worker_arenas;
            worker_arenas.reserve(static_cast<size_t>(num_evo_workers));
            for (int i = 0; i < num_evo_workers; ++i) {
                worker_arenas.push_back(std::make_unique<tbb::task_arena>(num_multilevel_threads));
            }
            return worker_arenas;
        };

        const auto reached_global_stop_condition = [&]() {
            const auto now = std::chrono::duration_cast<std::chrono::milliseconds>(
              std::chrono::high_resolution_clock::now().time_since_epoch());
            if (enforce_time_limit && (now - time_start >= duration)) {
                stop_flag = true;
                return true;
            }
            if (context.evolutionary.max_iterations != 0 &&
                total_iterations.load(std::memory_order_relaxed) >= context.evolutionary.max_iterations) {
                stop_flag = true;
                return true;
            }
            return false;
        };


        const int global_seed = context.partition.seed;
        //standard mode non-deterministic
        if (!context.partition.deterministic) {
            // task arenas for each worker to ensure isolated thread pools
            auto worker_arenas = create_worker_arenas();

            tbb::parallel_for(0, num_evo_workers, [&](int worker_id) {
                // Each evo worker uses own arena
                worker_arenas[worker_id]->execute([&] {
                    while (!stop_flag) {
                        if (reached_global_stop_condition()) {
                            break;
                        }
                        if (context.evolutionary.improvement_rate_stopping.enabled) {
                            std::unique_lock<std::mutex> stop_lock(stopping_criterion_mutex, std::try_to_lock);
                            if (stop_lock.owns_lock()) {
                                const std::vector<evolutionary::ImprovementLogEntry> improvements = stats.improvements();
                                const int last_improv_iter = improvements.empty() ? -1 : improvements.back().iteration;

                                bool should_stop = evolutionary::stopping::sliding_window_improvement_rate_stop(
                                    last_improv_iter,
                                    improvements,
                                    total_iterations.load(),
                                    context.evolutionary.improvement_rate_stopping.early_window_improvs,
                                    context.evolutionary.improvement_rate_stopping.recent_window_improvs,
                                    context.evolutionary.improvement_rate_stopping.alpha,
                                    context.evolutionary.improvement_rate_stopping.max_iters_without_improv,
                                    early_window_improvement_rate
                                );

                                if (should_stop) {
                                    stop_flag = true;
                                    break;
                                }
                            }
                        }

                        // Create a context for the inner run and set its thread limit
                        Context evo_context(context);
                        evo_context.type = ContextType::main;
                        evo_context.utility_id = utils::Utilities::instance().registerNewUtilityObjects();
                        evo_context.shared_memory.num_threads = num_multilevel_threads;

                        EvoDecision decision = pick::decideNextMove(context);
                        EvoPartitioner<TypeTraits>::Hypergraph hg_copy = hg.copy(parallel_tag_t{});

                        // Ensure sanityCheck preconditions hold for any standard partitioning
                        // calls executed within workers by keeping part weights vector empty
                        // unless individual part weights are explicitly enabled by the user.
                        if (!evo_context.partition.use_individual_part_weights) {
                            evo_context.partition.max_part_weights.clear();
                        }
                        
                        switch (decision) {
                            case EvoDecision::mutation:
                                {
                                    auto mut_result = performMutation(hg_copy, evo_context, target_graph, population);
                                    insert_individual_into_population(mut_result.individual, evo_context, population, stats, log,
                                        total_iterations.load() + 1, evolutionary::toEvoOperator(mut_result.strategy),
                                        mut_result.parent_best_fitness, mut_result.dist_to_parent);
                                    total_iterations++;
                                    break;
                                }
                            case EvoDecision::combine:
                                {
                                    const CombineResult result = performCombine(hg_copy, evo_context, target_graph, population, modified_combine_params);
                                    insert_individual_into_population(result.individual, evo_context, population, stats, log,
                                        total_iterations.load() + 1, evolutionary::toEvoOperator(result.strategy),
                                        result.parent_best_fitness, result.dist_to_parent);
                                    total_iterations++;
                                    break;
                                }
                            default:
                                LOG << "Error in evo_partitioner.cpp: Non-covered case in decision making";
                                std::exit(EXIT_FAILURE);
                        }
                    }
                });
            });
        }
        else {
            //determinstic mode
            const int batch_size = context.evolutionary.batch_size;
            std::vector<std::shared_ptr<Individual>> batch_individuals (batch_size);
            std::vector<evolutionary::EvoOperator> batch_operators(batch_size);
            std::atomic<size_t> last_batch_filled = 0;
            std::atomic<int> items_finished_in_current_batch = 0;

            auto worker_arenas = create_worker_arenas();

            tbb::parallel_for(0, num_evo_workers, [&](int worker_id) {
                // Each evo worker uses its own arena
                worker_arenas[worker_id]->execute([&] {

                    while (!stop_flag) {
                        if (reached_global_stop_condition()) {
                            break;
                        }

                        int iteration_id = -1;
                        int batch_id = -1;
                        int batch_pos = -1;
                        while (true) {
                            const int cur = total_iterations.load(std::memory_order_relaxed);
                            const int cur_batch = cur / batch_size;

                            while (static_cast<size_t>(cur_batch) > last_batch_filled.load(std::memory_order_acquire)) {
                                if (stop_flag.load(std::memory_order_acquire)) {
                                    break;
                                }
                                std::this_thread::yield();
                            }
                            if (stop_flag.load(std::memory_order_acquire)) {
                                break;
                            }

                            int expected = cur;
                            if (total_iterations.compare_exchange_weak(expected, cur + 1, std::memory_order_acq_rel, std::memory_order_relaxed)) {
                                iteration_id = cur;
                                batch_id = cur_batch;
                                batch_pos = cur % batch_size;
                                break;
                            }
                        }
                        if (stop_flag.load(std::memory_order_acquire)) {
                            break;
                        }

                        // Create a thread-local copy of the context
                        Context evo_context(context);
                        evo_context.type = ContextType::main;
                        evo_context.utility_id = utils::Utilities::instance().registerNewUtilityObjects();
                        evo_context.shared_memory.num_threads = num_multilevel_threads;


                        evo_context.partition.seed = global_seed + iteration_id;

                        // Initialize task-local RNG
                        std::mt19937 rng(evo_context.partition.seed);

                        EvoDecision decision = pick::decideNextMove(evo_context, &rng);
                        Hypergraph hg_copy = hg.copy(parallel_tag_t{});
                        std::shared_ptr<Individual> child;

                        evolutionary::EvoOperator op;
                        switch (decision) {
                            case EvoDecision::mutation: {
                                auto mut_result = performMutation(hg_copy, evo_context, target_graph, population, &rng);
                                op = evolutionary::toEvoOperator(mut_result.strategy);
                                child = std::move(mut_result.individual);
                                break;
                            }
                            case EvoDecision::combine: {
                                auto result = performCombine(hg_copy, evo_context, target_graph, population, modified_combine_params, &rng);
                                op = evolutionary::toEvoOperator(result.strategy);
                                child = std::move(result.individual);
                                break;
                            }
                            default:
                                LOG << "Error: Non-covered case in decision making";
                                std::exit(EXIT_FAILURE);
                        }

                        // Store individual in batch
                        batch_individuals[static_cast<size_t>(batch_pos)] = std::move(child);
                        batch_operators[static_cast<size_t>(batch_pos)] = op;
                        
                        int finished_count = items_finished_in_current_batch.fetch_add(1, std::memory_order_acq_rel) + 1;

                        if (finished_count == batch_size) {
                            // Insert entire batch into population
                            for (size_t i = 0; i < batch_size; ++i) {
                                const int current_batch_start_id = batch_id * batch_size;
                                HyperedgeWeight p_fit = batch_individuals[i]->parentBestFitness();
                                size_t p_dist = batch_individuals[i]->distToParent();
                                insert_individual_into_population(std::make_unique<Individual>(std::move(*batch_individuals[i])), evo_context, population, stats, log,
                                    current_batch_start_id + static_cast<int>(i) + 1, batch_operators[i], p_fit, p_dist);
                            }

                            // Deterministic stopping criterion evaluation at batch boundaries
                            if (context.evolutionary.improvement_rate_stopping.enabled &&
                                !stop_flag.load(std::memory_order_acquire)) {
                                std::lock_guard<std::mutex> stop_lock(stopping_criterion_mutex);
                                const std::vector<evolutionary::ImprovementLogEntry> improvements = stats.improvements();
                                const int last_improv_iter = improvements.empty() ? -1 : improvements.back().iteration;

                                const bool should_stop = evolutionary::stopping::sliding_window_improvement_rate_stop(
                                    last_improv_iter,
                                    improvements,
                                    (batch_id + 1) * batch_size,
                                    context.evolutionary.improvement_rate_stopping.early_window_improvs,
                                    context.evolutionary.improvement_rate_stopping.recent_window_improvs,
                                    context.evolutionary.improvement_rate_stopping.alpha,
                                    context.evolutionary.improvement_rate_stopping.max_iters_without_improv,
                                    early_window_improvement_rate
                                );

                                if (should_stop) {
                                    stop_flag.store(true, std::memory_order_release);
                                }
                            }

                            // Mark batch as filled
                            items_finished_in_current_batch.store(0, std::memory_order_release);
                            last_batch_filled.fetch_add(1, std::memory_order_release);
                        } 

                    } 
                });
            });
        }



        timer.stop_timer("evolutionary");

        // Final diff matrix
        log.recordDiffMatrix(population);

        context.evolutionary.iteration += total_iterations.load();
        context.partition.enable_logging = true;
        reportStatistics(context, stats, population, total_iterations.load());
    }

    template<typename TypeTraits>
    void EvoPartitioner<TypeTraits>::reportStatistics(const Context& context,
                                                      const evolutionary::EvoStatistics& stats,
                                                      const Population& population,
                                                      const int total_iterations) {
        using evolutionary::EvoOperator;
        const evolutionary::OperatorStats basic = stats.operatorStats(EvoOperator::basic_combine);
        const evolutionary::OperatorStats edge_freq = stats.operatorStats(EvoOperator::edge_frequency_combine);
        const evolutionary::OperatorStats synthetic = stats.operatorStats(EvoOperator::synthetic_parent_combine);
        const evolutionary::OperatorStats vcycle = stats.operatorStats(EvoOperator::vcycle_mutation);
        const evolutionary::OperatorStats new_ip = stats.operatorStats(EvoOperator::new_ip_mutation);
        const uint64_t total_mutations = vcycle.attempts + new_ip.attempts;
        const uint64_t total_combinations = basic.attempts + edge_freq.attempts + synthetic.attempts;
        utils::Stats& utility_stats = utils::Utilities::instance().getStats(context.utility_id);

        LOG << "Performed " << total_iterations << " Evolutionary Iterations";
        LOG << "  " << total_mutations << " Mutations";
        LOG << "  " << total_combinations << " Combinations";
        utility_stats.add_stat("evo_iterations", static_cast<int64_t>(total_iterations));
        utility_stats.add_stat("evo_mutations", static_cast<int64_t>(total_mutations));
        utility_stats.add_stat("evo_combinations", static_cast<int64_t>(total_combinations));
        if (context.evolutionary.basic_combine_weight > 0) {
            LOG << "    " << basic.attempts << " Basic";
            utility_stats.add_stat("evo_basic_combinations", static_cast<int64_t>(basic.attempts));
        }
        if (context.evolutionary.edge_frequency_combine_weight > 0) {
            LOG << "    " << edge_freq.attempts << " Edge Frequency";
            utility_stats.add_stat("evo_edge_frequency_combinations", static_cast<int64_t>(edge_freq.attempts));
        }
        if (context.evolutionary.synthetic_parent_combine_weight > 0) {
            LOG << "    " << synthetic.attempts << " Synthetic Parent";
            utility_stats.add_stat("evo_synthetic_parent_combinations", static_cast<int64_t>(synthetic.attempts));
        }
        LOG << "===================================================";
        LOG << "Operator Yield Statistics";
        const auto print_op_stat = [&](const std::string& name, const evolutionary::OperatorStats& op_stats) {
            double rate = op_stats.attempts > 0 ? (static_cast<double>(op_stats.accepted) / op_stats.attempts) * 100.0 : 0.0;
            LOG << "  " << name << ": " << op_stats.attempts << " attempts | " << op_stats.accepted << " accepted (" << rate << "%)";
        };
        print_op_stat("Basic Combine", basic);
        print_op_stat("Edge Frequency Combine", edge_freq);
        print_op_stat("Synthetic Parent Combine", synthetic);
        print_op_stat("vCycle Mutation", vcycle);
        print_op_stat("New Initial Part Mutation", new_ip);

        LOG << "===================================================";
        LOG << "Population Slot Replacement Heatmap";
        std::vector<size_t> slot_reps = population.slotReplacements();
        size_t untouched_slots = 0;
        size_t max_reps = 0;
        for (size_t i = 0; i < slot_reps.size(); ++i) {
            if (slot_reps[i] == 0) untouched_slots++;
            if (slot_reps[i] > max_reps) max_reps = slot_reps[i];
        }
        LOG << "  Total slots: " << slot_reps.size() << " | Untouched (alive since init): " << untouched_slots << " | Max overwrites on single slot: " << max_reps;

        LOG << "===================================================";
        LOG << "Insertion Statistics";
        LOG << "  " << population.total_insert_attempts.load() << " total insertion attempts";
        LOG << "  " << population.accepted_replacement.load() << " accepted insertions";
        LOG << "  " << population.rejected_worse_than_worst.load() << " rejected because worse than worst";
        const size_t total = population.total_insert_attempts.load();
        const size_t rejected = population.rejected_worse_than_worst.load();
        const double percentage = total > 0 ? (static_cast<double>(rejected) / total) * 100.0 : 0.0;
        LOG << "  " << percentage << "% rejection percentage";

        utility_stats.add_stat("evo_basic_combine_attempts", static_cast<int64_t>(basic.attempts));
        utility_stats.add_stat("evo_basic_combine_accepted", static_cast<int64_t>(basic.accepted));
        utility_stats.add_stat("evo_edge_freq_combine_attempts", static_cast<int64_t>(edge_freq.attempts));
        utility_stats.add_stat("evo_edge_freq_combine_accepted", static_cast<int64_t>(edge_freq.accepted));
        utility_stats.add_stat("evo_synthetic_combine_attempts", static_cast<int64_t>(synthetic.attempts));
        utility_stats.add_stat("evo_synthetic_combine_accepted", static_cast<int64_t>(synthetic.accepted));
        utility_stats.add_stat("evo_vcycle_mutation_attempts", static_cast<int64_t>(vcycle.attempts));
        utility_stats.add_stat("evo_vcycle_mutation_accepted", static_cast<int64_t>(vcycle.accepted));
        utility_stats.add_stat("evo_new_init_mutation_attempts", static_cast<int64_t>(new_ip.attempts));
        utility_stats.add_stat("evo_new_init_mutation_accepted", static_cast<int64_t>(new_ip.accepted));

        utility_stats.add_stat("evo_insertion_attempts", static_cast<int64_t> (population.total_insert_attempts.load()));
        utility_stats.add_stat("evo_accepted_replacements", static_cast<int64_t>(population.accepted_replacement.load()));
        utility_stats.add_stat("evo_rejected_worse_than_worst", static_cast<int64_t>(population.rejected_worse_than_worst.load()));
        utility_stats.add_stat("evo_rejection_percentage", percentage);
    }

